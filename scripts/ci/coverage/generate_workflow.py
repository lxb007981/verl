"""Generate the separate collector from Ascend PR jobs, or check it for drift.

Run with: uv run --no-project --python 3.12 --no-build --with PyYAML==6.0.2
    python scripts/ci/coverage/generate_workflow.py [--check]
"""

import argparse
import copy
import json
import re
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[3]
DESTINATION = ROOT / ".github/workflows/coverage-collection-npu.yml"
HELPER = "scripts/ci/coverage/collect.py"
HEADER = "# Generated by scripts/ci/coverage/generate_workflow.py; do not edit by hand.\n"


class ActionsLoader(yaml.SafeLoader):
    """Keep YAML 1.2's 'on' key while retaining actual boolean values."""


ActionsLoader.yaml_implicit_resolvers = copy.deepcopy(yaml.SafeLoader.yaml_implicit_resolvers)
for first, resolvers in ActionsLoader.yaml_implicit_resolvers.items():
    ActionsLoader.yaml_implicit_resolvers[first] = [item for item in resolvers if item[0] != "tag:yaml.org,2002:bool"]
ActionsLoader.add_implicit_resolver("tag:yaml.org,2002:bool", re.compile(r"^(?:true|false)$", re.I), list("tTfF"))


class ActionsDumper(yaml.SafeDumper):
    """Render run blocks as literal YAML for review."""


def represent_string(dumper, value):
    """Preserve newlines and avoid folded shell commands."""
    return dumper.represent_scalar("tag:yaml.org,2002:str", value, style="|" if "\n" in value else None)


ActionsDumper.add_representer(str, represent_string)


def source_workflows():
    """Discover PR workloads, excluding collection, image builds and docs."""
    for path in sorted((ROOT / ".github/workflows").glob("*.y*ml")):
        if not (path.name.endswith("_ascend.yml") or path.name == "npu_unit_tests.yml"):
            continue
        source = yaml.load(path.read_text(encoding="utf-8"), Loader=ActionsLoader)
        if "pull_request" in source.get("on", {}):
            yield path, source


def workload(step):
    """Classify original run steps; require review for new kinds of setup steps."""
    if "run" not in step:
        return False
    name = step.get("name", "").lower()
    if name.startswith(("check ", "install ", "prepare weights", "clean up")):
        return False
    if not any(token in step["run"] for token in ("tests/", "examples/", "-m verl.", "run_pytest_suite")):
        raise ValueError(f"Unclassified run step: {step.get('name')}")
    return True


def collect_job(path, source, job_id, job_names):
    """Copy one job, instrument workload steps, and append raw artifact retention."""
    job = copy.deepcopy(source["jobs"][job_id])
    if "strategy" in job or "uses" in job:
        raise ValueError(f"Review matrix/reusable job before collecting {path.name}/{job_id}")
    original_condition = job.get("if", "true")
    condition = str(original_condition).removeprefix("${{").removesuffix("}}").strip()
    job["if"] = "${{ github.repository_owner == 'verl-project' && (" + condition + ") }}"
    needs = job.get("needs", [])
    if isinstance(needs, str):
        needs = [needs]
    job["needs"] = ["validate", *(job_names[name] for name in needs)]
    job["name"] = f"{path.name} / {job_id}"
    timeout = job.get("timeout-minutes", 60)
    if path.name == "npu_unit_tests.yml":
        timeout = 60  # Original non-coverage-mode PR timeout.
    if not isinstance(timeout, int):
        raise ValueError(f"Review dynamic timeout for {path.name}/{job_id}")
    job["timeout-minutes"] = min(timeout * 2 + 30, 360)
    if source.get("defaults"):
        job["defaults"] = {**source["defaults"], **job.get("defaults", {})}
    job["env"] = {**source.get("env", {}), **job.get("env", {})}
    job["env"] = {key: str(value) for key, value in job["env"].items()}
    job["env"].update(
        VERL_COVERAGE_ROOT="${{ github.workspace }}/.ci-coverage/${{ github.run_id }}-${{ github.run_attempt }}/"
        + job_names[job_id]
        + "/data",
        VERL_COVERAGE_WORKFLOW=path.name,
        VERL_COVERAGE_JOB=job_id,
    )
    steps, plan = [], []
    initialized = False
    for index, step in enumerate(job.pop("steps")):
        # Only copy the PR execution path from the tentative NPU coverage implementation.
        if path.name == "npu_unit_tests.yml" and "coverage_mode == true" in str(step.get("if", "")):
            continue
        if path.name == "npu_unit_tests.yml" and step.get("if") == "inputs.coverage_mode != true":
            del step["if"]
        if workload(step):
            if step.get("shell") or step.get("working-directory"):
                raise ValueError(f"Review custom shell/directory for {path.name}/{job_id}/{index}")
            if not initialized:
                steps.append(
                    {
                        "name": "Initialize branch coverage collection",
                        "run": "command -v uv >/dev/null || python -m pip install uv\n"
                        "uv pip install --python \"$(python -c 'import sys; print(sys.executable)')\" "
                        '"coverage==7.8.2"\n'
                        f"python {HELPER} init\n",
                        "shell": "bash",
                    }
                )
                initialized = True
            step_id = f"step-{index:02d}"
            plan.append(
                {
                    "id": step_id,
                    "name": step["name"],
                    "entrypoints": sorted(set(re.findall(r"(?:tests|examples)/[\w./-]+\.(?:sh|py)", step["run"]))),
                    # Preprocessors can legitimately execute no verl code.
                    "requires_verl_coverage": "examples/data_preprocess/" not in step["run"],
                }
            )
            # A custom shell wraps the entire run block, including Ray startup, heredocs,
            # environment assignments and repeated invocations. Original run text is unchanged.
            step["shell"] = f"python {HELPER} run {step_id} {{0}}"
        steps.append(step)
    if not plan:
        raise ValueError(f"No workloads found in {path.name}/{job_id}")
    job["env"]["VERL_COVERAGE_PLAN"] = json.dumps(plan)
    steps.extend(
        [
            {
                "name": "Package raw coverage (including partial runs)",
                "if": "${{ always() }}",
                "shell": "bash",
                "run": f"python {HELPER} package",
            },
            {
                "name": "Retain raw coverage artifact",
                "if": "${{ always() }}",
                "uses": "actions/upload-artifact@v4",
                "with": {
                    "name": "ascend-coverage-" + job_names[job_id] + "-${{ github.run_attempt }}",
                    "path": "${{ env.VERL_COVERAGE_ROOT }}/../coverage.tar.gz",
                    "compression-level": 0,
                    "if-no-files-found": "warn",
                    "retention-days": 14,
                },
            },
        ]
    )
    job["steps"] = steps
    return job


def generate():
    """Render all source jobs with their original dependency relationships."""
    workflows = list(source_workflows())
    workflow = {
        "name": "Coverage Collection (Ascend PR workloads)",
        "on": {
            "workflow_dispatch": None,
            # Temporary validation trigger; remove after the first collection is inspected.
            "pull_request": {
                "branches": ["main", "v0.*"],
                "paths": [
                    DESTINATION.relative_to(ROOT).as_posix(),
                    "scripts/ci/**",
                    *[path.relative_to(ROOT).as_posix() for path, _ in workflows],
                ],
            },
            # 05:00 UTC+8 on alternate days of the month, not a strict 48-hour timer.
            "schedule": [{"cron": "0 21 */2 * *"}],
        },
        "permissions": {"contents": "read"},
        "concurrency": {"group": "ascend-coverage-${{ github.ref }}", "cancel-in-progress": False},
        "jobs": {
            "validate": {
                "if": "github.repository_owner == 'verl-project'",
                "runs-on": "ubuntu-latest",
                "steps": [
                    {"uses": "actions/checkout@v4"},
                    {"uses": "astral-sh/setup-uv@v6"},
                    {
                        "name": "Check collection workflow matches PR workloads",
                        "run": "uv run --no-project --python 3.12 --no-build --with PyYAML==6.0.2 "
                        "python scripts/ci/coverage/generate_workflow.py --check",
                    },
                ],
            }
        },
    }
    for path, source in workflows:
        names = {job_id: f"{path.stem}__{index}" for index, job_id in enumerate(source["jobs"], 1)}
        for job_id in source["jobs"]:
            workflow["jobs"][names[job_id]] = collect_job(path, source, job_id, names)
    return HEADER + yaml.dump(workflow, Dumper=ActionsDumper, sort_keys=False, width=120)


def main():
    """Write the generated workflow or fail with regeneration instructions."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = generate()
    if args.check:
        if DESTINATION.read_text(encoding="utf-8") != generated:
            raise SystemExit("Coverage workflow is stale; run scripts/ci/coverage/generate_workflow.py")
        print("Coverage workflow matches all Ascend PR source jobs.")
    else:
        DESTINATION.write_text(generated, encoding="utf-8", newline="\n")
        print(f"Generated {DESTINATION.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
